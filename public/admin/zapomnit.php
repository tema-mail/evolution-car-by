<?php
/**
 * «Запомнить меня» для кабинета. Просьба владельца 08.11.2026: не вводить
 * пароль при каждом заходе со своего компьютера.
 *
 * Как это работает. Файл лежит внутри каталога, закрытого паролем Apache,
 * поэтому до его кода запрос доходит только после верного логина – проверять
 * пароль заново не нужно и нечем. Здесь мы ставим долгую метку в браузер, а
 * admin/.htaccess пускает с ней без пароля.
 *
 * Почему метка, а не «запомнить пароль в браузере»: в кабинете лежат заявки
 * с именами и телефонами, то есть персональные данные. Метка:
 *   HttpOnly – её не прочитает никакой скрипт на странице;
 *   Secure   – уходит только по https;
 *   SameSite=Strict – не отправляется при переходах с чужих сайтов;
 *   значение – случайные 32 байта, лежат файлом вне каталога сайта.
 * Снять метку на этом устройстве: /admin/vyyti.php.
 */
declare(strict_types=1);

const SECRET_FILE = '/var/www/h221108/data/admin-cookie-secret';
const DAYS = 180;

$secret = @file_get_contents(SECRET_FILE);
if ($secret === false || trim($secret) === '') {
    http_response_code(500);
    exit('Ключ не найден на сервере. Пароль продолжает работать, скажите об этом в чате.');
}

setcookie('ec_admin', trim($secret), [
    'expires' => time() + DAYS * 86400,
    'path' => '/',
    'secure' => true,
    'httponly' => true,
    'samesite' => 'Strict',
]);

header('Location: /');
?>
<!doctype html>
<meta charset="utf-8">
<title>Запомнили</title>
<p>Запомнили этот браузер на 180 дней. <a href="/">Вернуться в кабинет</a></p>
