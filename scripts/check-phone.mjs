// Проверка поля телефона: что уходит в заявку при разных способах ввода.
// Запуск (нужен node 22+, он исполняет TypeScript напрямую):
//
//   node scripts/check-phone.mjs
//
// Почему это есть: номер часто вставляют целиком, в местной записи и без
// плюса. Раньше поле оставалось на выбранной стране, и российский номер
// уезжал в белорусскую маску – 89131234567 превращался в +375 91 312-34-56,
// заявка приходила с номером, по которому не дозвониться. Проверка ловит
// возврат этой ошибки.
import { parsePhoneInput, fullPhone, nationalFilled } from '../src/lib/phone.ts';

const cases = [
  // [что вводят, какая страна выбрана в поле, что должно уйти в заявку]
  ['89131234567', 'BY', '+7 913 123-45-67'],
  ['79131234567', 'BY', '+7 913 123-45-67'],
  ['84951234567', 'BY', '+7 495 123-45-67'],
  ['80291234567', 'RU', '+375 29 123-45-67'],
  ['80291234567', 'BY', '+375 29 123-45-67'],
  ['80171234567', 'BY', '+375 17 123-45-67'],
  ['291234567', 'BY', '+375 29 123-45-67'],
  ['375291234567', 'BY', '+375 29 123-45-67'],
  ['+79131234567', 'BY', '+7 913 123-45-67'],
  ['+375291234567', 'RU', '+375 29 123-45-67'],
];

let bad = 0;
for (const [input, startIso, want] of cases) {
  const { iso, national } = parsePhoneInput(input, startIso);
  const got = fullPhone(national, iso);
  const filled = nationalFilled(national, iso);
  const ok = got === want && filled;
  if (!ok) bad += 1;
  const note = filled ? '' : ' [номер считается неполным]';
  console.log(
    `${ok ? 'ок  ' : 'МИМО'} ${input.padEnd(14)} (выбрана ${startIso}) -> ${got.padEnd(20)}${note}` +
      (ok ? '' : ` ждали ${want}`),
  );
}

console.log(bad ? `\nошибок: ${bad}` : '\nвсе случаи прошли');
process.exit(bad ? 1 : 0);
